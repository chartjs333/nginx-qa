#!/usr/bin/env python3
"""Compare per-channel AR-order summaries within one person. Not clinical inference.

Input: AR JSON files generated by analyze_eeg_ar.py, provided as CODE:FILE pairs.
B1 and B2 must both be provided to anchor the test/retest baseline.
"""
import argparse,json
from pathlib import Path
from statistics import median

def compare(items):
    if 'B1' not in items or 'B2' not in items:
        raise ValueError('Both B1 and B2 baseline sessions are mandatory')
    result={'baseline_sessions':['B1','B2'],'result':'descriptive only',
            'caveat':'AR-order differences alone are not evidence of organ improvement or treatment efficacy',
            'channels':{}}
    channels=set(items['B1']['channels']) & set(items['B2']['channels'])
    for ch in sorted(channels):
        a=items['B1']['channels'][ch].get('median_order')
        b=items['B2']['channels'][ch].get('median_order')
        if a is None or b is None:continue
        ref=median([a,b]); baseline_delta=abs(a-b)
        records={}
        for session,obj in items.items():
            signal=obj['channels'].get(ch,{})
            v=signal.get('median_order')
            records[session]={'median_order':v,'delta_from_two_baselines':None if v is None else v-ref,
                              'n_accepted_windows':signal.get('n_accepted')}
        result['channels'][ch]={'reference_median_order':ref,'baseline_absolute_test_retest_difference':baseline_delta,
                                'sessions':records}
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--session',action='append',required=True,help='Session in form B1:result.json, B2:result.json, P1:result.json, etc.')
    p.add_argument('--out',required=True)
    args=p.parse_args(); data={}
    for item in args.session:
        if ':' not in item:p.error('Expected CODE:FILE')
        name,path=item.split(':',1)
        if name in data:p.error('Duplicate session: '+name)
        data[name]=json.loads(Path(path).read_text(encoding='utf-8'))
    out=compare(data)
    Path(args.out).write_text(json.dumps(out,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print('Written:',args.out)
if __name__=='__main__':main()